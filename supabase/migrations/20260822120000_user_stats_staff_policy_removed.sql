-- Политика «Staff can view customer stats» отдавала всю таблицу user_stats
-- любому партнёру, бариста и модератору — без привязки к кофейне:
--
--   has_role(partner) OR has_role(barista) OR has_role(moderator)
--
-- На практике это означало, что каждый из 55 сотрудников мог одним запросом
-- к REST API забрать балансы, серии, гостевой кофе и бонусные баллы всех 518
-- пользователей. Имён и телефонов там нет — они в profiles, и profiles
-- разграничены правильно.
--
-- Политика не нужна ни одному экрану. Проверено перед удалением:
--   * в коде user_stats читают только useUserStats (всегда с eq('user_id',
--     свой id) — это закрывает политика «Users can view their own stats»)
--     и админка (закрывает «Admins can view all stats»);
--   * в кабинетах партнёра и бариста обращений к таблице нет вовсе;
--   * сканер берёт остаток из ответа edge-функции, а та ходит служебным
--     ключом в обход RLS;
--   * все 7 функций базы, работающих с таблицей, — SECURITY DEFINER,
--     то есть RLS к ним не применяется;
--   * представлений над таблицей нет, в публикацию realtime она не входит.
--
-- Модератор доступ сохраняет: он остаётся в политике «Admins can view all
-- stats». Теряют доступ ровно партнёр и бариста, что и требовалось.

DROP POLICY IF EXISTS "Staff can view customer stats" ON public.user_stats;
