-- Договоры с кофейнями были доступны любому человеку со ссылкой: бакет
-- shop-contracts создавался публичным, а поверх висело правило чтения без единого
-- условия на пользователя. Загружать документы мог только администратор — а
-- скачать мог кто угодно, и авторизация для этого не требовалась вовсе.
--
-- Закрываем бакет. Читать теперь могут только администратор и модератор (правило
-- «Admins manage shop-contracts» уже это даёт), а в интерфейсе файл открывается по
-- временной подписанной ссылке на несколько минут.
--
-- Публичные ссылки, сохранённые в shops.contract_file_url, после этого перестают
-- работать напрямую — приложение распознаёт их и приводит к пути хранилища, так
-- что уже загруженные договоры продолжают открываться.

UPDATE storage.buckets SET public = false WHERE id = 'shop-contracts';

DROP POLICY IF EXISTS "Public read shop-contracts" ON storage.objects;
