/**
 * Название напитка так, как его должна видеть кофейня.
 *
 * Признак «это гостевой кофе» хранится прямо в тексте drink_name — отдельной
 * колонки в redemptions нет. За годы накопилось два формата:
 *   «Гостевой кофе от ID:821488»
 *   «Гостевой доступ → ID: 485793»
 *
 * Партнёру и бариста эта подробность не нужна: для кофейни это обычное
 * списание, которое так же оплачивается. Кому гость и от кого — дело
 * пользователя и владельца, поэтому в личной истории и в админке текст
 * остаётся как есть. Запись в базе не меняется: она источник правды для
 * обеих сторон, и переписывать её ради экрана нельзя.
 */
export function drinkLabelForStaff(drinkName: string | null | undefined): string {
  if (!drinkName) return 'Кофе';
  return /^\s*гостев/i.test(drinkName) ? 'Кофе' : drinkName;
}
