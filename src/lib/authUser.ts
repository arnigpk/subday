import { supabase } from '@/integrations/supabase/client';
import type { User } from '@supabase/supabase-js';

/**
 * Текущий пользователь — из локальной сессии, без похода в сеть.
 *
 * `supabase.auth.getUser()` выглядит дешёвым, но КАЖДЫЙ вызов идёт на сервер
 * проверять токен. При открытии главной десяток хуков зовут его одновременно, и
 * в логах это выглядело как 593 запроса `/auth/v1/user` за три часа с четырёх
 * устройств, пиками до 11 в секунду. На быстром вайфае незаметно, на мобильной
 * связи данные появляются заметно позже.
 *
 * Нам почти везде нужен только `user_id`, чтобы построить запрос за своими
 * данными. Для этого достаточно `getSession()` — он читает сохранённую сессию
 * локально. Безопасность от этого не страдает: что человеку можно увидеть,
 * решает RLS на сервере, а не то, что клиент думает о себе. Подделав id у себя
 * в браузере, чужие данные всё равно не получить.
 *
 * Форма ответа намеренно повторяет `getUser()` — чтобы места вызова менялись
 * один в один, без правки разбора результата.
 */
export async function getAuthUser(): Promise<{ data: { user: User | null }; error: null }> {
  const { data: { session } } = await supabase.auth.getSession();
  return { data: { user: session?.user ?? null }, error: null };
}
